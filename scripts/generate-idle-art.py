#!/usr/bin/env python3
"""Generate the native Crimson brush-ring idle background (no runtime decoding)."""
import math
import random
from pathlib import Path
from PIL import Image, ImageDraw
root = Path(__file__).resolve().parents[1]
rng = random.Random(18)
im = Image.new('RGB', (320, 240), '#040709')
d = ImageDraw.Draw(im)
for i in range(620):
    radius = rng.uniform(73, 117)
    start = rng.uniform(-158, -40)
    end = start + rng.uniform(85, 280)
    points = []
    for j in range(int(end-start)):
        a = math.radians(start+j)
        r = radius + math.sin(a*5+i)*rng.uniform(0, 3)
        points.append((160+math.cos(a)*r*1.12, 105+math.sin(a)*r))
    red = rng.randrange(55, 205)
    if len(points)>1:d.line(points, fill=(red, int(red*.09), int(red*.12)), width=rng.choice([1,1,2]))
for _ in range(2800):
    x,y=rng.randrange(320),rng.randrange(205)
    r=((x-160)/1.12)**2+(y-105)**2
    if 68**2<r<122**2 and rng.random()<.7:d.point((x,y),fill='#09090a')
# Layered jagged mountain silhouettes and sparse warm ridgelines.
for layer,base in enumerate([181,194,205]):
    ridge=[]
    for x in range(0,325,4):
        y=base-int(22*math.sin(x*.025+layer)**6)-rng.randrange(0,9)
        ridge.append((x,y))
    d.polygon([(0,240)]+ridge+[(320,240)],fill=(7+layer*2,8+layer,9+layer))
    d.line(ridge,fill=(66-layer*11,49-layer*8,36-layer*6),width=1)
    for x,y in ridge:
        if rng.random()<.3:d.line([(x,y),(x-8,y+12),(x-22,y+24)],fill='#29231f')
im.save(root/'ui/assets/crimson-idle.png')
values=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.getdata()]
with (root/'ui/assets/crimson-idle.h').open('w') as out:
    out.write('/* Generated by scripts/generate-idle-art.py. */\nstatic const unsigned short idle_art[320*240]={\n')
    for i in range(0,len(values),16):out.write(','.join(hex(n) for n in values[i:i+16])+',\n')
    out.write('};\n')
